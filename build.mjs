// 1. Copies the sketches in hardware/ into dist/sensor-code.mjs (shown in the site's hardware popups).
// 2. Bundles dist/ into the single self-contained transitsense.html.
// Usage: node build.mjs
import {readFileSync, writeFileSync} from 'node:fs';

const url = path => new URL(path, import.meta.url);
const read = path => readFileSync(url(path), 'utf8');

const sketches = {
  'junction_warning.ino': './hardware/junction_warning/junction_warning.ino',
  'siren_priority.ino': './hardware/siren_priority/siren_priority.ino',
  'magnetic_counter.ino': './hardware/magnetic_counter/magnetic_counter.ino',
  'parking_camera.ino': './hardware/parking_camera/parking_camera.ino',
  'bay_predictor.py': './hardware/parking_server/bay_predictor.py',
};
const code = Object.fromEntries(Object.entries(sketches).map(([name, path]) => [name, read(path)]));
writeFileSync(url('./dist/sensor-code.mjs'), '// Generated by build.mjs from hardware/. Edit the sketches there, then run: node build.mjs\nexport default ' + JSON.stringify(code, null, 1) + ';\n');

// Bare names the bundled modules import each other by (resolved through the import map).
const modules = {
  three: './dist/vendor/three.module.js',
  orbit: './dist/vendor/OrbitControls.js',
  model: './dist/model.mjs',
  traffic: './dist/traffic.mjs',
  siren: './dist/siren.mjs',
  sensorcode: './dist/sensor-code.mjs',
  hardware: './dist/hardware.mjs',
  live: './dist/live.mjs',
  dashboard: './dist/dashboard.mjs',
};
const specifiers = {
  './vendor/OrbitControls.js': 'orbit',
  './model.mjs': 'model',
  './traffic.mjs': 'traffic',
  './siren.mjs': 'siren',
  './sensor-code.mjs': 'sensorcode',
  './hardware.mjs': 'hardware',
  './live.mjs': 'live',
  './dashboard.mjs': 'dashboard',
};
const rewrite = source => source.replace(/from '(\.\/[^']+)'/g, (match, path) => specifiers[path] ? `from '${specifiers[path]}'` : match);
const dataUrl = path => 'data:text/javascript;base64,' + (path.includes('/vendor/three') ? readFileSync(url(path)) : Buffer.from(rewrite(read(path)))).toString('base64');
const imports = Object.fromEntries(Object.entries(modules).map(([name, path]) => [name, dataUrl(path)]));

const swap = (html, find, replacement) => {
  if (!html.includes(find)) throw new Error('build: marker not found: ' + find);
  return html.replace(find, () => replacement);
};
let html = read('./dist/index.html');
html = swap(html, '<link rel="stylesheet" href="style.css">', '<style>' + read('./dist/style.css') + '</style>');
html = swap(html, /<script type="importmap">.*?<\/script>/s.exec(html)[0], '<script type="importmap">{"imports": {' + Object.entries(imports).map(([k, v]) => JSON.stringify(k) + ': ' + JSON.stringify(v)).join(', ') + '}}</script>');
html = swap(html, '<script type="module" src="app.js"></script>', '<script type="module">' + rewrite(read('./dist/app.js')) + '</script>');

writeFileSync(url('./transitsense.html'), html);
console.log('Built dist/sensor-code.mjs and transitsense.html (' + (html.length / 1024 / 1024).toFixed(2) + ' MB)');
